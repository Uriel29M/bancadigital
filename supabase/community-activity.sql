-- Registro público temporário da atividade da comunidade.
-- Diferente de notifications, não possui destinatário e não gera badge.
create table if not exists public.community_activity (
  id bigint generated by default as identity primary key,
  actor_id uuid references public.profiles(id) on delete set null,
  event_type text not null check (event_type in ('comment', 'completed', 'like')),
  title text not null check (char_length(title) between 1 and 160),
  body text not null check (char_length(body) between 1 and 1000),
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null default (now() + interval '24 hours')
);

create index if not exists community_activity_created_idx on public.community_activity(created_at desc);
create index if not exists community_activity_expires_idx on public.community_activity(expires_at);

create or replace function public.purge_expired_community_activity()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  delete from public.community_activity where expires_at <= now();
  return new;
end;
$$;

drop trigger if exists purge_expired_community_activity_trigger on public.community_activity;
create trigger purge_expired_community_activity_trigger
before insert on public.community_activity
for each statement execute procedure public.purge_expired_community_activity();
revoke execute on function public.purge_expired_community_activity() from anon, authenticated;

create or replace function public.record_community_activity(
  p_actor_id uuid,
  p_event_type text,
  p_title text,
  p_body text,
  p_metadata jsonb default '{}'::jsonb
)
returns void language plpgsql security definer set search_path = public
as $$
begin
  if p_actor_id is null then return; end if;
  insert into public.community_activity(actor_id, event_type, title, body, metadata)
  values (p_actor_id, p_event_type, left(p_title, 160), left(p_body, 1000), coalesce(p_metadata, '{}'::jsonb));
end;
$$;

revoke execute on function public.record_community_activity(uuid, text, text, text, jsonb) from anon, authenticated;

create or replace function public.record_comic_comment_activity()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  perform public.record_community_activity(NEW.user_id, 'comment', 'Novo comentário', NEW.body,
    jsonb_build_object('source', 'comic', 'item_id', NEW.item_id, 'comment_id', NEW.id));
  return NEW;
end;
$$;

