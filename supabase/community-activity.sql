create or replace function public.record_completion_activity()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  if NEW.completed and (TG_OP = 'INSERT' or not coalesce(OLD.completed, false)) then
    perform public.record_community_activity(NEW.user_id, 'completed', 'História concluída', 'Alguém concluiu uma história.',
      jsonb_build_object('source', 'comic', 'item_id', NEW.item_id));
  end if;
  return NEW;
end;
$$;

drop trigger if exists record_completion_activity_trigger on public.reading_progress;
create trigger record_completion_activity_trigger after insert or update of completed on public.reading_progress for each row execute procedure public.record_completion_activity();
revoke execute on function public.record_completion_activity() from anon, authenticated;

alter table public.community_activity enable row level security;
grant select on public.community_activity to authenticated;
drop policy if exists "community activity is public" on public.community_activity;
create policy "community activity is public" on public.community_activity for select using (
  expires_at > now() and auth.uid() is not null and (actor_id is null or not public.is_blocked_between(actor_id))
);
