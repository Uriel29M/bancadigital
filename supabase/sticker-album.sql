create table if not exists public.sticker_awards (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  character_id text not null,
  character_name text not null,
  publisher_name text not null,
  edition_fingerprint text not null,
  cover_item_id text not null,
  cover_url text not null check (cover_url ~ '^https://|^data:image/'),
  rarity text not null default 'standard' check (rarity in ('standard', 'torn', 'creased', 'silver', 'gold')),
  awarded_at timestamptz not null default now(),
  unique (user_id, character_id, edition_fingerprint)
);
alter table public.sticker_awards drop constraint if exists sticker_awards_rarity_check;
alter table public.sticker_awards add constraint sticker_awards_rarity_check check (rarity in ('standard', 'torn', 'creased', 'silver', 'gold'));
create index if not exists sticker_awards_user_idx on public.sticker_awards(user_id, character_name);
create index if not exists sticker_awards_character_idx on public.sticker_awards(character_id, awarded_at desc);
alter table public.sticker_awards add column if not exists album_section text not null default 'pasted';
alter table public.sticker_awards drop constraint if exists sticker_awards_album_section_check;
alter table public.sticker_awards add constraint sticker_awards_album_section_check check (album_section in ('pasted', 'repeated'));
with ranked as (
  select id, row_number() over (partition by user_id, character_id order by awarded_at desc, id desc) as position
  from public.sticker_awards
)
update public.sticker_awards awards
set album_section = case when ranked.position = 1 then 'pasted' else 'repeated' end
from ranked
where ranked.id = awards.id;

create table if not exists public.sticker_claim_history (
  user_id uuid not null references public.profiles(id) on delete cascade,
  character_id text not null,
  edition_fingerprint text not null,
  first_claimed_at timestamptz not null default now(),
  primary key (user_id, character_id, edition_fingerprint)
);
insert into public.sticker_claim_history(user_id, character_id, edition_fingerprint, first_claimed_at)
select user_id, character_id, edition_fingerprint, min(awarded_at)
from public.sticker_awards
group by user_id, character_id, edition_fingerprint
on conflict (user_id, character_id, edition_fingerprint) do nothing;
alter table public.sticker_claim_history enable row level security;
drop policy if exists "users read own sticker claim history" on public.sticker_claim_history;
create policy "users read own sticker claim history" on public.sticker_claim_history for select using (auth.uid() = user_id);

create table if not exists public.sticker_requests (
  id bigint generated by default as identity primary key,
  requester_id uuid not null references public.profiles(id) on delete cascade,
  owner_id uuid not null references public.profiles(id) on delete cascade,
  character_id text not null,
  character_name text not null,
  edition_fingerprint text not null,
  request_type text not null check (request_type in ('gift', 'trade')),
  offered_award_id bigint references public.sticker_awards(id) on delete set null,
  status text not null default 'pending' check (status in ('pending', 'accepted', 'declined', 'cancelled')),
  created_at timestamptz not null default now(),
  resolved_at timestamptz,
  check (requester_id <> owner_id),
  check (request_type = 'gift' or offered_award_id is not null or status <> 'pending')
);
alter table public.sticker_requests drop constraint if exists sticker_requests_check1;
