create or replace function public.set_sticker_album_section(p_award_id bigint, p_section text)
returns public.sticker_awards
language plpgsql security definer set search_path = public
as $$
declare
  v_award public.sticker_awards;
  v_current public.sticker_awards;
begin
  if auth.uid() is null or p_section not in ('pasted', 'repeated') then raise exception 'Seção do álbum inválida'; end if;
  select * into v_award from public.sticker_awards where id = p_award_id and user_id = auth.uid() for update;
  if not found then raise exception 'Figurinha não encontrada'; end if;
  if p_section = 'pasted' then
    select * into v_current
    from public.sticker_awards
    where user_id = auth.uid()
      and character_id = v_award.character_id
      and album_section = 'pasted'
      and id <> v_award.id
    order by awarded_at desc, id desc
    limit 1
    for update;
    if v_current.id is not null then
      update public.sticker_awards set album_section = 'repeated' where id = v_current.id;
    end if;
  end if;
  update public.sticker_awards set album_section = p_section where id = v_award.id returning * into v_award;
  return v_award;
end;
