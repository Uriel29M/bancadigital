create or replace function public.claim_character_sticker(
  p_character_id text,
  p_character_name text,
  p_publisher_name text,
  p_edition_fingerprint text,
  p_edition_ids jsonb,
  p_cover_item_id text,
  p_cover_url text
)
returns public.sticker_awards
language plpgsql security definer set search_path = public
as $$
declare
  v_award public.sticker_awards;
  v_completed integer;
  v_total integer;
  v_roll integer;
  v_existing public.sticker_awards;
  v_previous public.sticker_awards;
  v_previous_2 public.sticker_awards;
  v_cover_item_id text;
  v_cover_url text;
begin
  if auth.uid() is null then raise exception 'É preciso estar autenticado'; end if;
  -- Impede duas cargas simultâneas de concederem a mesma figurinha.
  perform pg_advisory_xact_lock(hashtext(auth.uid()::text || ':' || p_character_id || ':' || p_edition_fingerprint));
  if nullif(trim(p_character_id), '') is null or nullif(trim(p_character_name), '') is null
    or nullif(trim(p_publisher_name), '') is null or nullif(trim(p_edition_fingerprint), '') is null
    or nullif(trim(p_cover_item_id), '') is null or nullif(trim(p_cover_url), '') is null
    or jsonb_typeof(p_edition_ids) <> 'array' or jsonb_array_length(p_edition_ids) = 0
  then raise exception 'Dados da figurinha inválidos'; end if;
  if p_cover_url !~ '^https://|^data:image/' then raise exception 'Capa da figurinha inválida'; end if;

  select count(*) into v_total from jsonb_array_elements_text(p_edition_ids);
  select count(*) into v_completed
  from public.reading_progress progress
  where progress.user_id = auth.uid()
    and progress.completed
    and progress.item_id in (select value from jsonb_array_elements_text(p_edition_ids));
  if v_total <> v_completed then raise exception 'Todas as edições do personagem precisam estar lidas'; end if;
  if exists (select 1 from public.sticker_awards where user_id = auth.uid() and character_id = p_character_id and edition_fingerprint = p_edition_fingerprint) then
    select * into v_award from public.sticker_awards where user_id = auth.uid() and character_id = p_character_id and edition_fingerprint = p_edition_fingerprint limit 1;
    return v_award;
  end if;
  if exists (select 1 from public.sticker_claim_history where user_id = auth.uid() and character_id = p_character_id and edition_fingerprint = p_edition_fingerprint) then
    raise exception 'Esta versão da figurinha já foi conquistada; aguarde uma nova edição do personagem';
  end if;

  v_roll := floor(random() * 100)::integer;
  v_cover_item_id := p_cover_item_id;
  v_cover_url := p_cover_url;
  select * into v_existing
  from public.sticker_awards
  where user_id = auth.uid() and character_id = p_character_id
  order by awarded_at desc, id desc
  limit 1;
  select * into v_previous
  from public.sticker_awards
  where user_id = auth.uid() and character_id = p_character_id
  order by awarded_at desc, id desc
  offset 0 limit 1;
  select * into v_previous_2
  from public.sticker_awards
  where user_id = auth.uid() and character_id = p_character_id
  order by awarded_at desc, id desc
  offset 1 limit 1;
  if v_existing.id is not null
    and not (v_previous.id is not null and v_previous_2.id is not null and v_previous.cover_url = v_previous_2.cover_url)
    and random() < 0.70
  then
    v_cover_item_id := v_existing.cover_item_id;
    v_cover_url := v_existing.cover_url;
  end if;
  if v_previous.id is not null and v_previous_2.id is not null
    and v_previous.cover_url = v_previous_2.cover_url
    and v_cover_url = v_previous.cover_url
  then
    raise exception 'A mesma imagem não pode sair três vezes seguidas';
  end if;
  insert into public.sticker_claim_history(user_id, character_id, edition_fingerprint)
  values (auth.uid(), p_character_id, p_edition_fingerprint);
  insert into public.sticker_awards(user_id, character_id, character_name, publisher_name, edition_fingerprint, cover_item_id, cover_url, rarity, album_section)
  values (auth.uid(), p_character_id, left(trim(p_character_name), 160), left(trim(p_publisher_name), 160), left(trim(p_edition_fingerprint), 500), left(trim(v_cover_item_id), 200), left(trim(v_cover_url), 2000), case when v_roll < 2 then 'gold' when v_roll < 7 then 'silver' when v_roll < 17 then 'creased' when v_roll < 35 then 'torn' else 'standard' end, case when exists (select 1 from public.sticker_awards where user_id = auth.uid() and character_id = p_character_id and album_section = 'pasted') then 'repeated' else 'pasted' end)
  returning * into v_award;
  return v_award;
end;
$$;
grant execute on function public.claim_character_sticker(text, text, text, text, jsonb, text, text) to authenticated;

create or replace function public.create_sticker_request(
  p_owner_id uuid,
  p_character_id text,
  p_character_name text,
  p_edition_fingerprint text,
  p_request_type text,
  p_offered_award_id bigint default null
)
returns public.sticker_requests
language plpgsql security definer set search_path = public
as $$
declare
  v_request public.sticker_requests;
  v_owner_username text;
begin
  if auth.uid() is null or p_owner_id is null or p_owner_id = auth.uid() then raise exception 'Pedido inválido'; end if;
  if p_request_type not in ('gift', 'trade') then raise exception 'Tipo de pedido inválido'; end if;
  -- Mantém a primeira oferta preenchida mesmo se o cliente enviar apenas
  -- a segunda posição por causa de estado antigo do seletor visual.
  if p_request_type = 'trade' and p_offered_award_id is null and p_offered_award_id_2 is not null then
    p_offered_award_id := p_offered_award_id_2;
    p_offered_award_id_2 := null;
  end if;
  if (select count(*) from public.sticker_requests where owner_id = p_owner_id and status = 'pending') >= 50 then raise exception 'Este álbum atingiu o limite de 50 pedidos pendentes'; end if;
  if (select count(*) from public.sticker_requests where requester_id = auth.uid() and status = 'pending') >= 20 then raise exception 'Você atingiu o limite de 20 pedidos pendentes'; end if;
  if public.is_blocked_between(p_owner_id) then raise exception 'Este perfil não aceita interações com você'; end if;
  if not exists (select 1 from public.profiles where id = p_owner_id and allow_sticker_requests) then raise exception 'Este usuário bloqueou pedidos de figurinhas'; end if;
  if exists (select 1 from public.sticker_awards where user_id = auth.uid() and character_id = p_character_id and edition_fingerprint = p_edition_fingerprint) then raise exception 'Você já possui esta figurinha'; end if;
  if not exists (select 1 from public.sticker_awards where user_id = p_owner_id and character_id = p_character_id and edition_fingerprint = p_edition_fingerprint and not requests_blocked) then raise exception 'Esta figurinha não aceita solicitações'; end if;
  if p_request_type = 'trade' and not exists (select 1 from public.sticker_awards where id = p_offered_award_id and user_id = auth.uid()) then raise exception 'Escolha uma figurinha sua para oferecer'; end if;
  if exists (select 1 from public.sticker_requests where requester_id = auth.uid() and owner_id = p_owner_id and character_id = p_character_id and edition_fingerprint = p_edition_fingerprint and status = 'pending') then raise exception 'Você já enviou este pedido'; end if;
  insert into public.sticker_requests(requester_id, owner_id, character_id, character_name, edition_fingerprint, request_type, offered_award_id)
  values (auth.uid(), p_owner_id, left(trim(p_character_id), 160), left(trim(p_character_name), 160), left(trim(p_edition_fingerprint), 500), p_request_type, case when p_request_type = 'trade' then p_offered_award_id else null end)
  returning * into v_request;
  select username into v_owner_username from public.profiles where id = p_owner_id;
  perform public.create_notification(p_owner_id, 'sticker_request', case when p_request_type = 'trade' then 'Nova proposta de troca' else 'Pedido de figurinha' end, case when p_request_type = 'trade' then 'Alguém quer trocar uma figurinha pela sua figurinha de ' || left(trim(p_character_name), 160) || '.' else 'Alguém pediu sua figurinha de ' || left(trim(p_character_name), 160) || '.' end, auth.uid(), '?perfil=' || coalesce(v_owner_username, '') || '&album=1', jsonb_build_object('request_id', v_request.id, 'character_id', p_character_id, 'request_type', p_request_type));
  return v_request;
end;
$$;
grant execute on function public.create_sticker_request(uuid, text, text, text, text, bigint) to authenticated;

create or replace function public.respond_sticker_request(p_request_id bigint, p_status text)
returns public.sticker_requests
language plpgsql security definer set search_path = public
as $$
declare
  v_request public.sticker_requests;
  v_target public.sticker_awards;
  v_offer public.sticker_awards;
begin
  if auth.uid() is null or p_status not in ('accepted', 'declined') then raise exception 'Resposta inválida'; end if;
  select * into v_request from public.sticker_requests where id = p_request_id and owner_id = auth.uid() and status = 'pending' for update;
  if not found then raise exception 'Pedido não encontrado ou já respondido'; end if;
  if p_status = 'accepted' then
    select * into v_target from public.sticker_awards where user_id = v_request.owner_id and character_id = v_request.character_id and edition_fingerprint = v_request.edition_fingerprint order by awarded_at desc, id desc limit 1 for update;
    if not found then raise exception 'A figurinha solicitada não está mais disponível'; end if;
    if v_request.request_type = 'gift' then
      if exists (select 1 from public.sticker_awards where user_id = v_request.requester_id and character_id = v_target.character_id and edition_fingerprint = v_target.edition_fingerprint) then raise exception 'A pessoa já possui esta figurinha'; end if;
      delete from public.sticker_awards where id = v_target.id;
      insert into public.sticker_awards(user_id, character_id, character_name, publisher_name, edition_fingerprint, cover_item_id, cover_url, rarity)
      values (v_request.requester_id, v_target.character_id, v_target.character_name, v_target.publisher_name, v_target.edition_fingerprint, v_target.cover_item_id, v_target.cover_url, v_target.rarity);
    else
      select * into v_offer from public.sticker_awards where id = v_request.offered_award_id and user_id = v_request.requester_id for update;
      if not found then raise exception 'A figurinha oferecida não está mais disponível'; end if;
      if exists (select 1 from public.sticker_awards where user_id = v_request.requester_id and character_id = v_target.character_id and edition_fingerprint = v_target.edition_fingerprint) then raise exception 'A pessoa já possui esta figurinha'; end if;
      if exists (select 1 from public.sticker_awards where user_id = v_request.owner_id and character_id = v_offer.character_id and edition_fingerprint = v_offer.edition_fingerprint) then raise exception 'Você já possui a figurinha oferecida'; end if;
      delete from public.sticker_awards where id in (v_target.id, v_offer.id);
      insert into public.sticker_awards(user_id, character_id, character_name, publisher_name, edition_fingerprint, cover_item_id, cover_url, rarity)
      values (v_request.requester_id, v_target.character_id, v_target.character_name, v_target.publisher_name, v_target.edition_fingerprint, v_target.cover_item_id, v_target.cover_url, v_target.rarity),
             (v_request.owner_id, v_offer.character_id, v_offer.character_name, v_offer.publisher_name, v_offer.edition_fingerprint, v_offer.cover_item_id, v_offer.cover_url, v_offer.rarity);
    end if;
  end if;
  update public.sticker_requests set status = p_status, resolved_at = now() where id = v_request.id returning * into v_request;
  perform public.create_notification(v_request.requester_id, 'sticker_request_' || p_status, case when p_status = 'accepted' then 'Pedido de figurinha aceito' else 'Pedido de figurinha recusado' end, case when p_status = 'accepted' then 'Sua solicitação de ' || v_request.character_name || ' foi concluída.' else 'Sua solicitação de ' || v_request.character_name || ' foi recusada.' end, auth.uid(), '?album=1', jsonb_build_object('request_id', v_request.id, 'character_id', v_request.character_id));
  return v_request;
end;
$$;
grant execute on function public.respond_sticker_request(bigint, text) to authenticated;

-- Reforça a mesma regra no caminho de doação, inclusive para administradores.
create or replace function public.transfer_sticker_award(p_recipient_id uuid, p_award_id bigint)
returns public.sticker_awards language plpgsql security definer set search_path = public
as $$
declare v_character_id text;
begin
  select character_id into v_character_id from public.sticker_awards where id = p_award_id and user_id = auth.uid();
  if v_character_id is null then raise exception 'Figurinha não encontrada'; end if;
  if exists (select 1 from public.sticker_slot_preferences where user_id = p_recipient_id and character_id = v_character_id and blocked) then
    raise exception 'Este slot não aceita doações';
  end if;
  return public.donate_sticker_award(p_recipient_id, p_award_id);
end;
$$;
grant execute on function public.transfer_sticker_award(uuid, bigint) to authenticated;

