create or replace function public.create_sticker_request(
  p_owner_id uuid,
  p_character_id text,
  p_character_name text,
  p_edition_fingerprint text,
  p_request_type text,
  p_offered_award_id bigint default null,
  p_offered_award_id_2 bigint default null
)
returns public.sticker_requests
language plpgsql security definer set search_path = public
as $$
declare
  v_request public.sticker_requests;
  v_owner_username text;
begin
  if auth.uid() is null or p_owner_id is null or p_owner_id = auth.uid() then raise exception 'Pedido inválido'; end if;
  if p_request_type not in ('gift', 'trade') then raise exception 'Tipo de pedido inválido'; end if;
  if (select count(*) from public.sticker_requests where owner_id = p_owner_id and status = 'pending') >= 50 then raise exception 'Este álbum atingiu o limite de 50 pedidos pendentes'; end if;
  if (select count(*) from public.sticker_requests where requester_id = auth.uid() and status = 'pending') >= 20 then raise exception 'Você atingiu o limite de 20 pedidos pendentes'; end if;
  if public.is_blocked_between(p_owner_id) then raise exception 'Este perfil não aceita interações com você'; end if;
  if not exists (select 1 from public.profiles where id = p_owner_id and allow_sticker_requests) then raise exception 'Este usuário bloqueou pedidos de figurinhas'; end if;
  if exists (select 1 from public.sticker_awards where user_id = auth.uid() and character_id = p_character_id and edition_fingerprint = p_edition_fingerprint) then raise exception 'Você já possui esta figurinha'; end if;
  if not exists (select 1 from public.sticker_awards where user_id = p_owner_id and character_id = p_character_id and edition_fingerprint = p_edition_fingerprint and not requests_blocked) then raise exception 'Esta figurinha não aceita solicitações'; end if;
  if p_request_type = 'trade' and p_offered_award_id is null then raise exception 'Escolha uma figurinha para oferecer'; end if;
  if p_request_type = 'gift' and (p_offered_award_id is not null or p_offered_award_id_2 is not null) then raise exception 'Pedido de doação não pode oferecer figurinhas'; end if;
  if p_offered_award_id_2 is not null and p_offered_award_id_2 = p_offered_award_id then raise exception 'Escolha figurinhas diferentes'; end if;
  if p_request_type = 'trade' and not exists (select 1 from public.sticker_awards where id = p_offered_award_id and user_id = auth.uid()) then raise exception 'A primeira figurinha oferecida não está disponível'; end if;
  if p_offered_award_id_2 is not null and not exists (select 1 from public.sticker_awards where id = p_offered_award_id_2 and user_id = auth.uid()) then raise exception 'A segunda figurinha oferecida não está disponível'; end if;
  if exists (select 1 from public.sticker_requests where requester_id = auth.uid() and owner_id = p_owner_id and character_id = p_character_id and edition_fingerprint = p_edition_fingerprint and status = 'pending') then raise exception 'Você já enviou este pedido'; end if;
  insert into public.sticker_requests(requester_id, owner_id, character_id, character_name, edition_fingerprint, request_type, offered_award_id, offered_award_id_2)
  values (auth.uid(), p_owner_id, left(trim(p_character_id), 160), left(trim(p_character_name), 160), left(trim(p_edition_fingerprint), 500), p_request_type, case when p_request_type = 'trade' then p_offered_award_id else null end, case when p_request_type = 'trade' then p_offered_award_id_2 else null end)
  returning * into v_request;
  select username into v_owner_username from public.profiles where id = p_owner_id;
  perform public.create_notification(p_owner_id, 'sticker_request', 'Nova proposta de troca', 'Alguém enviou uma proposta de troca por sua figurinha de ' || left(trim(p_character_name), 160) || '.', auth.uid(), '?perfil=' || coalesce(v_owner_username, '') || '&album=1', jsonb_build_object('request_id', v_request.id, 'character_id', p_character_id, 'request_type', p_request_type, 'offered_count', case when p_offered_award_id_2 is null then 1 else 2 end));
  return v_request;
end;
$$;
grant execute on function public.create_sticker_request(uuid, text, text, text, text, bigint, bigint) to authenticated;
