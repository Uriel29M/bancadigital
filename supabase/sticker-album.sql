create or replace function public.prevent_blocked_sticker_requests()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  if exists (
    select 1 from public.sticker_slot_preferences
    where user_id = new.owner_id and character_id = new.character_id and blocked
  ) then
    raise exception 'Este slot não aceita pedidos ou trocas';
  end if;
  return new;
end;
$$;
