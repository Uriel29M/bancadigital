create or replace function public.respond_sticker_request(p_request_id bigint, p_status text)
returns public.sticker_requests
language plpgsql security definer set search_path = public
as $$
declare
  v_request public.sticker_requests;
  v_target public.sticker_awards;
  v_offer public.sticker_awards;
  v_offer2 public.sticker_awards;
begin
  if auth.uid() is null or p_status not in ('accepted', 'declined') then raise exception 'Resposta inválida'; end if;
  select * into v_request from public.sticker_requests where id = p_request_id and owner_id = auth.uid() and status = 'pending' for update;
  if not found then raise exception 'Pedido não encontrado ou já respondido'; end if;
  if p_status = 'accepted' then
    select * into v_target from public.sticker_awards where user_id = v_request.owner_id and character_id = v_request.character_id and edition_fingerprint = v_request.edition_fingerprint order by awarded_at desc, id desc limit 1 for update;
    if not found then raise exception 'A figurinha solicitada não está mais disponível'; end if;
    if v_request.request_type = 'gift' then
      if exists (select 1 from public.sticker_awards where user_id = v_request.requester_id and character_id = v_target.character_id and edition_fingerprint = v_target.edition_fingerprint) then raise exception 'A pessoa já possui esta figurinha'; end if;
      delete from public.sticker_awards where id = v_target.id;
      insert into public.sticker_awards(user_id, character_id, character_name, publisher_name, edition_fingerprint, cover_item_id, cover_url, rarity, album_section) values (v_request.requester_id, v_target.character_id, v_target.character_name, v_target.publisher_name, v_target.edition_fingerprint, v_target.cover_item_id, v_target.cover_url, v_target.rarity, case when exists (select 1 from public.sticker_awards where user_id = v_request.requester_id and character_id = v_target.character_id and album_section = 'pasted') then 'repeated' else 'pasted' end);
    else
      select * into v_offer from public.sticker_awards where id = v_request.offered_award_id and user_id = v_request.requester_id for update;
      if not found then raise exception 'A figurinha oferecida não está mais disponível'; end if;
      if v_request.offered_award_id_2 is not null then
        select * into v_offer2 from public.sticker_awards where id = v_request.offered_award_id_2 and user_id = v_request.requester_id for update;
        if not found then raise exception 'A segunda figurinha oferecida não está mais disponível'; end if;
      end if;
      if exists (select 1 from public.sticker_awards where user_id = v_request.requester_id and character_id = v_target.character_id and edition_fingerprint = v_target.edition_fingerprint) then raise exception 'A pessoa já possui esta figurinha'; end if;
      if exists (select 1 from public.sticker_awards where user_id = v_request.owner_id and character_id = v_offer.character_id and edition_fingerprint = v_offer.edition_fingerprint) or (v_offer2.id is not null and exists (select 1 from public.sticker_awards where user_id = v_request.owner_id and character_id = v_offer2.character_id and edition_fingerprint = v_offer2.edition_fingerprint)) then raise exception 'Você já possui uma das figurinhas oferecidas'; end if;
      delete from public.sticker_awards where id in (v_target.id, v_offer.id, v_offer2.id);
      insert into public.sticker_awards(user_id, character_id, character_name, publisher_name, edition_fingerprint, cover_item_id, cover_url, rarity, album_section) values (v_request.requester_id, v_target.character_id, v_target.character_name, v_target.publisher_name, v_target.edition_fingerprint, v_target.cover_item_id, v_target.cover_url, v_target.rarity, case when exists (select 1 from public.sticker_awards where user_id = v_request.requester_id and character_id = v_target.character_id and album_section = 'pasted') then 'repeated' else 'pasted' end);
      insert into public.sticker_awards(user_id, character_id, character_name, publisher_name, edition_fingerprint, cover_item_id, cover_url, rarity, album_section) values (v_request.owner_id, v_offer.character_id, v_offer.character_name, v_offer.publisher_name, v_offer.edition_fingerprint, v_offer.cover_item_id, v_offer.cover_url, v_offer.rarity, case when exists (select 1 from public.sticker_awards where user_id = v_request.owner_id and character_id = v_offer.character_id and album_section = 'pasted') then 'repeated' else 'pasted' end);
      if v_offer2.id is not null then insert into public.sticker_awards(user_id, character_id, character_name, publisher_name, edition_fingerprint, cover_item_id, cover_url, rarity, album_section) values (v_request.owner_id, v_offer2.character_id, v_offer2.character_name, v_offer2.publisher_name, v_offer2.edition_fingerprint, v_offer2.cover_item_id, v_offer2.cover_url, v_offer2.rarity, case when exists (select 1 from public.sticker_awards where user_id = v_request.owner_id and character_id = v_offer2.character_id and album_section = 'pasted') then 'repeated' else 'pasted' end); end if;
    end if;
  end if;
  update public.sticker_requests set status = p_status, resolved_at = now() where id = v_request.id returning * into v_request;
  perform public.create_notification(v_request.requester_id, 'sticker_request_' || p_status, case when p_status = 'accepted' then 'Pedido de figurinha aceito' else 'Pedido de figurinha recusado' end, case when p_status = 'accepted' then 'Sua proposta de ' || v_request.character_name || ' foi concluída.' else 'Sua proposta de ' || v_request.character_name || ' foi recusada.' end, auth.uid(), '?album=1', jsonb_build_object('request_id', v_request.id, 'character_id', v_request.character_id));
  return v_request;
end;
$$;
grant execute on function public.respond_sticker_request(bigint, text) to authenticated;
